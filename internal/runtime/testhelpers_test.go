package runtime

import (
	"bufio"
	"net"
	"testing"
)

func freePort(t *testing.T) int {
	t.Helper()
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	port := ln.Addr().(*net.TCPAddr).Port
	_ = ln.Close()
	return port
}

func reader(conn net.Conn) *bufio.Reader { return bufio.NewReader(conn) }
