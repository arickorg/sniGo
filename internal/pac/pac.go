// Package pac generates the Proxy Auto-Config script exactly like Rust's pac.rs:
// exact domains use an object lookup, wildcards use dnsDomainIs, paused returns DIRECT.
package pac

import (
	"fmt"
	"net"
	"sort"
	"strings"

	"github.com/arick/hakimi-gop/internal/config"
)

func CacheToken(script string) string {
	var hash uint32 = 0x811c9dc5
	for i := 0; i < len(script); i++ {
		hash ^= uint32(script[i])
		hash *= 0x01000193
	}
	return fmt.Sprintf("%06x", hash&0x00ffffff)
}

func BaseURL(addr net.Addr) string {
	return fmt.Sprintf("http://%s/proxy.pac", addr.String())
}

func VersionedURL(addr net.Addr, script string) string {
	return fmt.Sprintf("%s?v=%s", BaseURL(addr), CacheToken(script))
}

func SameURL(a, b string) bool {
	cut := func(s string) string {
		if i := strings.IndexByte(s, '?'); i >= 0 {
			return s[:i]
		}
		return s
	}
	return cut(a) == cut(b)
}

func Generate(cfg *config.AppConfig, proxy string, paused bool) string {
	proxyHost := proxy
	if host, port, err := net.SplitHostPort(proxy); err == nil {
		if ip := net.ParseIP(host); ip != nil && ip.To4() == nil {
			proxyHost = fmt.Sprintf("[%s]:%s", host, port)
		}
	}
	direct := fmt.Sprintf("PROXY %s; DIRECT", proxyHost)

	exact, wild := map[string]bool{}, map[string]bool{}
	if !paused {
		for _, g := range cfg.EnabledGroups() {
			for _, r := range g.Domains {
				p := strings.ToLower(strings.TrimSuffix(strings.TrimSpace(r.Pattern), "."))
				if strings.HasPrefix(p, "*.") {
					wild[p[2:]] = true
				} else if p != "" {
					exact[p] = true
				}
			}
		}
	}

	var b strings.Builder
	b.WriteString("// Generated by hakimi-gop. Do not edit.\n")
	if len(exact) > 0 {
		b.WriteString("var exact = {\n")
		keys := sortedKeys(exact)
		for _, k := range keys {
			fmt.Fprintf(&b, "  %q: 1,\n", escapeJS(k))
		}
		b.WriteString("};\n")
	}
	if len(wild) > 0 {
		b.WriteString("var wild = [\n")
		for _, k := range sortedKeys(wild) {
			fmt.Fprintf(&b, "  %q,\n", "."+escapeJS(k))
		}
		b.WriteString("];\n")
	}
	b.WriteString("function FindProxyForURL(url, host) {\n  host = host.toLowerCase();\n")
	if len(exact) == 0 && len(wild) == 0 {
		b.WriteString("  return \"DIRECT\";\n")
	} else {
		if len(exact) > 0 {
			b.WriteString("  if (exact[host] === 1) {\n    return \"" + direct + "\";\n  }\n")
		}
		if len(wild) > 0 {
			b.WriteString("  for (var i = 0; i < wild.length; i++) {\n")
			b.WriteString("    if (dnsDomainIs(host, wild[i])) {\n      return \"" + direct + "\";\n    }\n  }\n")
		}
		b.WriteString("  return \"DIRECT\";\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func escapeJS(v string) string {
	v = strings.ReplaceAll(v, `\`, `\\`)
	v = strings.ReplaceAll(v, `"`, `\"`)
	v = strings.ReplaceAll(v, "\n", `\n`)
	return strings.ReplaceAll(v, "\r", `\r`)
}
